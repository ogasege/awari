/**
 * The generated part of `CREDITS.md`: data-set credits with glob lines
 * covering every pack file and one table row per bundled photo. Only
 * the text between the pack markers is ever rewritten.
 */
import type { Photo } from '../../src/lib/packs/types.ts';

/** Marker opening the generated region. */
export const MARK_BEGIN = '<!-- packs:begin -->';
/** Marker closing the generated region. */
export const MARK_END = '<!-- packs:end -->';

/**
 * Replaces the text between the markers with `region`. When the markers
 * are absent they are appended, with the region, after the existing
 * text; nothing outside the markers is ever changed.
 */
export function replaceRegion(text: string, region: string): string {
  const body = region.replace(/^\n+|\n+$/g, '');
  const begin = text.indexOf(MARK_BEGIN);
  const end = text.indexOf(MARK_END, begin + MARK_BEGIN.length);
  if (begin === -1 && text.indexOf(MARK_END) === -1) {
    const sep = text === '' ? '' : text.endsWith('\n') ? '\n' : '\n\n';
    return `${text}${sep}${MARK_BEGIN}\n${body}\n${MARK_END}\n`;
  }
  if (begin === -1 || end === -1) {
    throw new Error('CREDITS.md has only one pack marker; fix it by hand');
  }
  return `${text.slice(0, begin + MARK_BEGIN.length)}\n${body}\n${text.slice(end)}`;
}

/** Escapes a value for a Markdown table cell. */
export function cell(value: string): string {
  return value.replace(/\r?\n/g, ' ').replace(/\|/g, '\\|').trim();
}

/** One credited photo. */
export interface PhotoCredit {
  /** Path relative to `public/`, e.g. "packs/img/nigeria.jpg". */
  path: string;
  subject: string;
  photo: Photo;
}

/** Renders the credits region (without the markers). */
export function renderCredits(
  photos: readonly PhotoCredit[],
  retrieved: string,
): string {
  const rows = [...photos]
    .sort((a, b) => a.path.localeCompare(b.path))
    .map(
      ({ path, subject, photo }) =>
        `| ${path} | ${cell(subject)} | ${cell(photo.credit.author ?? '')} | ` +
        `${photo.credit.licence} | ${photo.credit.url} |`,
    );
  return [
    '## Content packs',
    '',
    `Generated by \`npm run packs\` (scripts/packs) from open data retrieved`,
    `on or before ${retrieved}. This section is rewritten on every build.`,
    '',
    '### Articles: Simple English Wikipedia',
    '',
    'Article text is from Simple English Wikipedia, licensed under',
    '[CC BY-SA 4.0](https://creativecommons.org/licenses/by-sa/4.0/). Each',
    'article file names its source page; text was split into sections and',
    'some back-matter sections were removed.',
    '',
    '- `packs/countries/*.json` (country articles and the pack index)',
    '- `packs/physics/*.json` (electricity articles and the pack index)',
    '',
    '### Facts: Wikidata',
    '',
    'Country facts in `packs/countries/facts.json` come from Wikidata,',
    'dedicated to the public domain under',
    '[CC0 1.0](https://creativecommons.org/publicdomain/zero/1.0/).',
    '',
    '### Timeline: Wikidata',
    '',
    '- `packs/timeline.json`: dates and labels read from Wikidata (CC0) for a',
    '  hand-picked list of items; each sentence is a fixed template filled',
    '  with those fields, and each event names its Wikidata page.',
    '',
    '### Atlas: Natural Earth',
    '',
    '- `packs/atlas/*.json`: country shapes from Natural Earth 1:110m',
    '  admin-0 countries (public domain, naturalearthdata.com), with',
    '  coordinates rounded and properties trimmed.',
    '',
    '### Dictionary: Open English WordNet',
    '',
    '- `packs/dictionary/*.json`: word senses from Open English WordNet',
    '  (github.com/globalwordnet/english-wordnet), licensed under',
    '  [CC BY 4.0](https://creativecommons.org/licenses/by/4.0/).',
    '',
    '### Manifest',
    '',
    '- `packs/manifest.json`: list of generated files (no third-party',
    '  content).',
    '',
    '### Photos: Wikimedia Commons',
    '',
    'Resized to at most 800 px. Each links to its Commons file page.',
    '',
    '| File | Subject | Author | Licence | Source |',
    '| --- | --- | --- | --- | --- |',
    ...rows,
  ].join('\n');
}
